export type UnitGroup = "NHT" | "PAR ISOM" | "FBP";
export type UnitKind = "column" | "vessel";

export interface UnitNozzle {
  mark: string;
  /** size in inches; "ID" for a vessel-ID flange / handhole, "-" when not stated */
  size: string;
  service: string;
  count: number;
}

export interface HeadSpec {
  type: string;
  thk: number;
}

export interface ColumnSection {
  dia: number;
  thk: number;
  /** trays in this section (0 for a packed section) */
  trays: number;
}

export interface PackingBed {
  size: string;
  depth: number;
  packing: string;
}

export interface ProjectUnit {
  tag: string;
  name: string;
  group: UnitGroup;
  kind: UnitKind;
  orientation: "V" | "H";
  service: string;
  /** Book3 "special service" column */
  special: string;
  /** design pressure, kg/cm²(g) — datasheet basis */
  pKgcm: number;
  /** full vacuum external design (Book3 "FV") */
  vacuum: boolean;
  tempC: number;
  mdmt: number;
  /** corrosion allowance, mm */
  ca: number;
  /** size string exactly as it appears on the equipment list */
  size: string;
  /** governing (largest) inside diameter, mm */
  dia: number;
  /** tangent-to-tangent length, mm */
  tt: number;
  shellThk: number;
  topHead: HeadSpec;
  botHead: HeadSpec;
  /** conical transition thickness, mm */
  coneThk?: number;
  /** stepped / multiple-diameter shell, top → bottom */
  sections?: ColumnSection[];
  class: string;
  rt: string;
  pwht: "Yes" | "No" | "MR";
  ladders: boolean;
  insulated: boolean;
  support: "skirt" | "saddle";
  /** number of trays per spec 307 (0 / undefined when none) */
  trays?: number;
  trayMat?: string;
  /** random / structured packing beds */
  beds?: PackingBed[];
  boot?: { nps: string; thk: number; headThk: number };
  demister?: number;
  coalescer?: number;
  vortex?: string;
  nozzles: string;
  notes?: string[];
  flags?: string[];
}

/** `MARK SIZE SERVICE[*count]` separated by "|" */
export function parseNozzles(src: string): UnitNozzle[] {
  return src
    .split("|")
    .map((t) => t.trim())
    .filter(Boolean)
    .map((tok) => {
      const m = /^(\S+)\s+(\S+)\s+(.*)$/.exec(tok);
      if (!m) return { mark: tok, size: "-", service: "", count: 1 };
      let service = m[3];
      let count = 1;
      const cm = /\s*\*(\d+)$/.exec(service);
      if (cm) {
        count = Number(cm[1]);
        service = service.slice(0, cm.index).trim();
      }
      return { mark: m[1], size: m[2], service, count };
    });
}

/** openings that are manways / flanged heads rather than pipe nozzles */
export const isManway = (n: UnitNozzle) => /manway|flanged head|handhole/i.test(n.service);
/** body flanges on the vessel shell (12-C02 F01/F03/F04/F06) are not nozzles */
export const isBodyFlange = (n: UnitNozzle) => /vessel id|body flange/i.test(n.service);

